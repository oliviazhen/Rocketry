# Unit conversions
R_TO_K = 5 / 9
BTU_S_IN2_TO_W_M2 = 1055.056 / 0.0254 ** 2
H_TO_SI = 1e-4 * BTU_S_IN2_TO_W_M2 / R_TO_K  # printed h (x1e-4 BTU/s in^2 F) -> W/m^2K
PSI_TO_PA = 6894.757
LB_TO_KG = 0.45359237


def build():
    rows = []
    for test, d in TESTS.items():
        n = min(len(d["qw"]), len(d["Tw"]), len(d["h"]))
        for i in range(n):
            qw, Tw, h, Te = d["qw"][i], d["Tw"][i], d["h"][i] * 1e-4, d["Te"][i]
            implied_Taw = Tw + qw / h
            expected_Taw = Te + 0.89 * (d["Tt"] - Te)
            rows.append(dict(
                test=test, approach_length_in=d["l"], station=i + 1, z_over_L=ZL[i],
                pt_Pa=d["pt"] * PSI_TO_PA, Tt_K=d["Tt"] * R_TO_K,
                mdot_kg_s=d["mdot"] * LB_TO_KG,
                qw_W_m2=qw * BTU_S_IN2_TO_W_M2, Tw_K=Tw * R_TO_K, Te_K=Te * R_TO_K,
                h_exp_W_m2K=d["h"][i] * H_TO_SI,
                qa_implied_Taw_K=implied_Taw * R_TO_K, qa_expected_Taw_K=expected_Taw * R_TO_K,
                qa_Taw_error=implied_Taw / expected_Taw - 1))
    df = pd.DataFrame(rows)
    df["qa_pass"] = df["qa_Taw_error"].abs() < 0.03
    return df


if __name__ == "__main__":
    df = build()
    df.to_csv("bmg_heat_transfer_data.csv", index=False)
    print(f"{len(df)} rows from {df.test.nunique()} tests")
    print("QA |Taw error| < 3%:", int(df.qa_pass.sum()), "pass,", int((~df.qa_pass).sum()), "fail")
    print(df.loc[~df.qa_pass, ["test", "station", "z_over_L", "qa_Taw_error"]].to_string())
    print("median |error| by test:")
    print(df.groupby("test").qa_Taw_error.apply(lambda s: s.abs().median()).round(4).to_string())
